// Returns { mtype, region, morph } for a hippocampome mtype id (region/morph may be undefined).
export function describeHippocampomeMtype(mtype) {
  const reg = regionOfNtype(mtype);
  return {
    mtype: MTYPE_NAMES[mtype] || "Unknown mtype",
    region: reg?.name,
    morph: reg ? (mtype <= reg.pyrTo ? "PYR" : "INT") : undefined,
  };
}

// CA1 SONATA gid ranges: [from, to, mtype, morph class, etype, layer]
const CA1_GID_RANGES = [
  [1, 261843, "SP_PC", "PYR", "cACpyr", "SP"],
  [261844, 262437, "TRI", "INT", "bAC", "SO"],
  [262438, 263959, "SCA", "INT", "bIR", "SR"],
  [263960, 264524, "PVBC", "INT", "bNAC", "SP"],
  [264525, 266046, "PPA", "INT", "bIR", "SLM"],
  [266047, 267332, "OLM", "INT", "bAC", "SO"],
  [267333, 279729, "NGF", "INT", "nGC", "SLM"],
  [279730, 284803, "IVY", "INT", "bSTUT", "SP"],
  [284804, 285359, "CCKBC", "INT", "bNAC", "SP"],
  [285360, 287388, "BS", "INT", "bNAC", "SP"],
  [287389, 287487, "BP", "INT", "bIR", "SR"],
  [287488, 288027, "BP", "INT", "nNAC", "SP"],
];

function gidRow(gid) {
  return CA1_GID_RANGES.find(([lo, hi]) => gid >= lo && gid <= hi);
}

export const getmtypeLabel = (gid) => gidRow(gid)?.[2] ?? "Unknown";
export const getmorphclassLabel = (gid) => gidRow(gid)?.[3] ?? "Unknown";
export const getetypeLabel = (gid) => gidRow(gid)?.[4] ?? "Unknown";
export const getlayerLabel = (gid) => gidRow(gid)?.[5] ?? "Unknown";
export const getregionLabel = (gid) => (gidRow(gid) ? "CA1" : "Unknown");
